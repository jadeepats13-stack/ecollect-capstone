-- Each truck stop the collector finished, per day (collector app: "Done at this stop").
-- A zone's pickup (pickup_log) is recorded once every stop serving it that day is done.
create table if not exists public.stop_visit (
  stop_visit_id        integer generated by default as identity primary key,
  collection_point_id  integer not null references public.collection_point (collection_point_id) on update cascade on delete cascade,
  garbage_collector_id integer references public.garbage_collector (garbage_collector_id) on update cascade on delete set null,
  visit_date           date not null,
  completed_at         timestamptz not null default now(),
  outcome              varchar(10) not null default 'done' check (outcome in ('done', 'missed')),
  missed_reason        varchar(40),          -- "Couldn't collect": why
  note                 text,
  load_level           smallint check (load_level between 1 and 4),   -- truck about 1/4, 1/2, 3/4 or full after the stop (estimate)
  field_report_id      integer,              -- the field report sent with a missed stop
  unique (collection_point_id, visit_date)
);

