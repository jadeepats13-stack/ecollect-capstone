-- Collector shifts (collector app: "Start shift" / "End shift"). Gives the truck's operating hours.
create table if not exists public.collector_shift (
  shift_id             integer generated by default as identity primary key,
  garbage_collector_id integer references public.garbage_collector (garbage_collector_id) on update cascade on delete set null,
  truck_id             integer references public.truck (truck_id) on update cascade on delete set null,
  started_at           timestamptz not null,
  ended_at             timestamptz,
  auto_ended           boolean not null default false,    -- closed by the system (forgot to end it)
  check (ended_at is null or ended_at >= started_at)
);
create unique index if not exists collector_shift_open on public.collector_shift (garbage_collector_id) where ended_at is null;
create index if not exists collector_shift_started on public.collector_shift (started_at);

